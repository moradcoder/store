export type TKey = keyof (typeof dict)["ar"];

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  dir: "rtl" | "ltr";
  t: (key: TKey) => string;
  pick: (row: Record<string, unknown> | null | undefined, field: string) => string;
  money: (value: number | string | null | undefined) => string;
};

const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored === "ar" || stored === "fr") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const value = useMemo<Ctx>(() => {
    const t = (key: TKey) => dict[lang][key] ?? key;
    return {
      lang,
      setLang,
      dir: lang === "ar" ? "rtl" : "ltr",
      t,
      pick: (row, field) => {
        if (!row) return "";
        const v = row[`${field}_${lang}`] ?? row[`${field}_fr`] ?? row[`${field}_ar`];
        return typeof v === "string" ? v : "";
      },
      money: (value) => {
        const n = Number(value ?? 0);
        const formatted = new Intl.NumberFormat(lang === "ar" ? "ar-MA" : "fr-MA", {
          maximumFractionDigits: n % 1 === 0 ? 0 : 2,
        }).format(n);
        return lang === "ar" ? `${formatted} د.م.` : `${formatted} MAD`;
      },
    };
  }, [lang, setLang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}

